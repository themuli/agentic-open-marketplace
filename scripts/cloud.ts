import { config } from 'dotenv';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { secureCloudEnvironment } from './secure-cloud-env.js';
config({ path: ['.env', '.env.local'], quiet: true });
const role = process.argv[2];
if (!['market', 'facilitator'].includes(role)) throw new Error('Usage: npm run cloud:deploy -- market|facilitator');
const links = JSON.parse(readFileSync('.aom/deployments.json', 'utf8'));
process.env.MARKET_MCP_URL ||= links.market.mcpUrl;
process.env.FACILITATOR_URL ||= links.facilitator.mcpUrl.replace(/\/mcp\/?$/, '');
await import('./prepare-deploy.js');
const publicEnvFile = secureCloudEnvironment(role, links[role].link.serverId);
mkdirSync('.mcp-use/cloud', { recursive: true });
writeFileSync('.mcp-use/cloud/link.json', JSON.stringify(links[role].link, null, 2));
const stdout = execFileSync(process.execPath, ['node_modules/mcp-use/dist/bin.js', 'deploy', '--no-github', '--env-file', publicEnvFile, '--yes', '--json'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'], timeout: 180000 });
const result = JSON.parse(stdout);
links[role] = { ...links[role], lastDeployment: result };
writeFileSync('.aom/deployments.json', JSON.stringify(links, null, 2));
console.log(JSON.stringify(result, null, 2));
